import type {
  DefinitionNode,
  DocumentNode,
  FragmentDefinitionNode,
  GraphQLSchema,
  OperationDefinitionNode,
} from 'graphql';

import { toDecisionQuery, toVariantsQuery } from '../core/variants/queries';
import { toSchemaInfo } from '../core/variants/schema';

type TypeRef = { name: string | null; ofType?: TypeRef };
type SchemaType = {
  name: string;
  ofType?: unknown;
  getFields?: () => Record<
    string,
    { name: string; args: { name: string }[]; type: unknown }
  >;
};

function typeRef(type: unknown): TypeRef {
  const value = type as { name?: string; ofType?: unknown };
  return value.ofType
    ? { name: null, ofType: typeRef(value.ofType) }
    : { name: value.name ?? null };
}

/**
 * The introspection shape `toSchemaInfo` reads, built through the schema's
 * own methods. graphql's `introspectionFromSchema` would reject a schema
 * created by another copy of `graphql` (codegen often loads its own), so this
 * plugin imports nothing from `graphql` at runtime.
 */
function introspect(schema: GraphQLSchema) {
  const types = Object.values(
    schema.getTypeMap() as unknown as Record<string, SchemaType>,
  ).map((type) => {
    const possible =
      'getTypes' in type || 'getInterfaces' in type
        ? schema.getPossibleTypes(type as never)
        : [];
    return {
      name: type.name,
      possibleTypes: possible.length
        ? possible.map((member) => ({ name: member.name }))
        : null,
      fields: type.getFields
        ? Object.values(type.getFields()).map((field) => ({
            name: field.name,
            args: (field.args ?? []).map((arg) => ({ name: arg.name })),
            type: typeRef(field.type),
          }))
        : null,
    };
  });
  return {
    __schema: {
      queryType: { name: schema.getQueryType()?.name ?? 'Query' },
      types,
    },
  } as unknown as Parameters<typeof toSchemaInfo>[0];
}

/** Fragment names spread anywhere inside `node`, nested spreads included. */
function spreadNames(node: unknown, into: Set<string>): Set<string> {
  if (Array.isArray(node)) {
    for (const child of node) spreadNames(child, into);
  } else if (node && typeof node === 'object') {
    const value = node as { kind?: string; name?: { value: string } };
    if (value.kind === 'FragmentSpread' && value.name) {
      into.add(value.name.value);
    }
    for (const [key, child] of Object.entries(node)) {
      if (key !== 'loc') spreadNames(child, into);
    }
  }
  return into;
}

/**
 * graphql-codegen plugin: for every named query that touches personalizable
 * fields, writes the variants query and the decision query as string
 * constants, `<Name>VariantsQuery` and `<Name>DecisionQuery`. For sites that
 * send queries with their own client and want the rewrites done at build
 * time instead of loading the schema at runtime.
 *
 * The decision query asks about every personalizable list of the query. When
 * the variants result is at hand at runtime, `toDecisionQuery(query, schema,
 * { from })` is smaller and faster for visitors Prepr has not seen before.
 *
 * Register it in codegen.ts: `plugins: ['@preprio/toolkit/graphql/codegen']`.
 *
 * @throws Error when two queries share a name, since their exports would
 *   collide.
 */
export function plugin(
  schema: GraphQLSchema,
  documents: { document?: DocumentNode }[],
  // graphql-codegen passes the plugin config; this plugin takes none.
  _config?: Record<string, never>,
): string {
  const info = toSchemaInfo(introspect(schema));
  const definitions: DefinitionNode[] = documents.flatMap((source) => [
    ...(source.document?.definitions ?? []),
  ]);
  const fragments = new Map<string, FragmentDefinitionNode>();
  for (const definition of definitions) {
    if (definition.kind === 'FragmentDefinition') {
      fragments.set(definition.name.value, definition);
    }
  }

  const lines = [
    '// Generated by @preprio/toolkit/graphql/codegen. Do not edit.',
  ];
  const seen = new Set<string>();
  for (const definition of definitions) {
    if (definition.kind !== 'OperationDefinition') continue;
    const operation = definition as OperationDefinitionNode;
    if (operation.operation !== 'query' || !operation.name) continue;
    const name = operation.name.value;
    if (seen.has(name)) {
      throw new Error(
        `@preprio/toolkit codegen: two queries are named "${name}"; rename one so their exports do not collide.`,
      );
    }
    seen.add(name);

    // The operation plus every fragment it reaches, and nothing else: Prepr
    // rejects a query with an unused fragment.
    const used = new Set<string>();
    const queue = [...spreadNames(operation, new Set())];
    while (queue.length) {
      const next = queue.pop()!;
      if (used.has(next) || !fragments.has(next)) continue;
      used.add(next);
      queue.push(...spreadNames(fragments.get(next), new Set()));
    }
    const document = {
      kind: 'Document',
      definitions: [operation, ...[...used].map((n) => fragments.get(n)!)],
    } as unknown as DocumentNode;

    const decision = toDecisionQuery(document, info);
    if (!decision) continue;
    lines.push(
      `export const ${name}VariantsQuery = ${JSON.stringify(toVariantsQuery(document, info))};`,
      `export const ${name}DecisionQuery = ${JSON.stringify(decision)};`,
    );
  }
  return lines.join('\n') + '\n';
}
